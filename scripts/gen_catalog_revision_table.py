"""Generate / extend ``songs/chart_revision_table.py`` (known PRIOR catalog chart revisions).

The stale-chart provenance rule (songs/chart_provenance.py) refreshes an unstamped
saved snapshot ONLY when its sections exactly equal a historic catalog revision of the
same song.  Whenever a catalog chart is corrected, append the chart as it was BEFORE
the correction:

    python scripts/gen_catalog_revision_table.py --baseline-root <checkout-or-worktree-before-fix> \\
        --title "Some Song" [--title "Another Song"]

With no ``--title`` the Wave 1/2 default list (DEFAULT_TITLES) is used.  Entries are
MERGED into the existing table (never dropped) .  The baseline checkout is only
read (subprocess).  An entry equal to the current chart is harmless (SAME wins first).
Fingerprints use ``songs.chart_provenance`` of THIS repo.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

DEFAULT_TITLES = [
    "Photograph", "Don't Stop Believin'", "Day Tripper", "Imagine", "Californication",
    "So What", "Take the A Train", "All the Things You Are", "Satin Doll", "All of Me",
    "Misty", "Meditation", "Vienna", "Just the Way You Are", "Uptown Girl",
    "Careless Whisper", "We Are the Champions", "Kiss Me", "Thinking Out Loud",
    "Come Together", "Heal the World", "Wave", "How Insensitive", "So Nice (Summer Samba)",
    "Autumn Leaves", "Fly Me to the Moon",
]

_DUMP = r"""
import json, sys
titles = json.loads(sys.argv[1])
def n(t):
    return " ".join(str(t).replace("’", "'").lower().split())
want = {n(t) for t in titles}
from song_catalog.catalog import load_song_catalog
out = []
for r in load_song_catalog()[3]:
    if isinstance(r, dict) and n(r.get("title", "")) in want:
        out.append({k: r.get(k) for k in ("genre", "title", "artist", "sections", "chart_versions")})
open(sys.argv[2], "w", encoding="utf-8").write(json.dumps(out))
"""


def _dump(root: Path, titles: list[str]) -> list[dict]:
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / "dump.json"
        subprocess.run(
            [sys.executable, "-c", _DUMP, json.dumps(titles), str(out)],
            cwd=str(root), check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        return json.loads(out.read_text(encoding="utf-8"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--baseline-root", required=True, help="checkout holding the PRE-correction catalog")
    ap.add_argument("--title", action="append", help="song title (repeatable); default = Wave 1/2 list")
    ap.add_argument("--out", default=str(REPO / "songs" / "chart_revision_table.py"))
    args = ap.parse_args()

    from songs.chart_provenance import chart_fingerprint, revision_key, versions_fingerprint

    titles = args.title or DEFAULT_TITLES
    old_rows = _dump(Path(args.baseline_root), titles)
    # Entries equal to the CURRENT chart are redundant (SAME is classified first) and would make the
    # table claim the live chart is a 'prior' revision, so they are skipped.
    current = {revision_key(r): (chart_fingerprint(r.get("sections")), versions_fingerprint(r.get("chart_versions")))
               for r in _dump(REPO, titles)}

    table: dict[str, list[tuple[str, str]]] = {}
    try:
        from songs.chart_revision_table import PRIOR_REVISIONS

        for k, v in PRIOR_REVISIONS.items():
            table[k] = [tuple(e) for e in v]
    except Exception:
        pass
    labels: dict[str, str] = {}
    for r in old_rows:
        key = revision_key(r)
        sec = chart_fingerprint(r.get("sections"))
        if not sec:
            continue  # NB: an entry equal to the current chart is harmless (classified SAME first)
        entry = (sec, versions_fingerprint(r.get("chart_versions")))
        if current.get(key) == entry:
            continue
        if entry not in table.setdefault(key, []):
            table[key].append(entry)
        labels[key] = f"{r['title']} - {r['artist']}"

    lines = [
        '"""GENERATED by scripts/gen_catalog_revision_table.py - do not hand-edit.',
        "",
        "Known PRIOR catalog chart revisions: genre|title|artist -> ((sections_fp, chart_versions_fp), ...).",
        "Used by songs.chart_provenance.is_known_prior_revision.  Append new entries (never remove) by",
        "re-running the script with --baseline-root pointing at a checkout BEFORE a catalog correction.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "PRIOR_REVISIONS: dict[str, tuple[tuple[str, str], ...]] = {",
    ]
    for key in sorted(table):
        lines.append(f"    {key!r}: (")
        for sec, ver in table[key]:
            lines.append(f"        ({sec!r}, {ver!r}),")
        lines.append("    ),")
    lines.append("}")
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {len(table)} songs, {sum(len(v) for v in table.values())} revisions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
